CREATE TABLE `partie` (
    `id` INT PRIMARY KEY AUTO_INCREMENT,
    `id_etat_jeu` INT NOT NULL,
    `language` VARCHAR(2) NOT NULL DEFAULT 'fr',
    `id_player_1` INT NOT NULL,
    `id_player_2` INT NOT NULL,
    `id_player_3` INT NULL DEFAULT NULL,
    `id_player_4` INT NULL DEFAULT NULL,
    `score_player_1`INT NULL DEFAULT 0,
    `score_player_2`INT NULL DEFAULT 0,
    `score_player_3`INT NULL DEFAULT 0,
    `score_player_4`INT NULL DEFAULT 0,
    `letter_bag` VARCHAR(105) NULL DEFAULT NULL,
    -- `letter_bag_used` VARCHAR(105) NULL DEFAULT NULL,
    `chevalet_player_1` VARCHAR(7) NULL DEFAULT NULL,
    `chevalet_player_2` VARCHAR(7) NULL DEFAULT NULL,
    `chevalet_player_3` VARCHAR(7) NULL DEFAULT NULL,
    `chevalet_player_4` VARCHAR(7) NULL DEFAULT NULL,
    `state` ENUM('waiting', 'in_progress', 'finished') DEFAULT 'waiting',
    `date_start` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `date_end` DATETIME NULL DEFAULT NULL,
    `turn_player` INT NULL DEFAULT 1 COMMENT '1 = player_1, 2 = player_2, 3 = player_3, 4 = player_4, 0 = game done'
)

